# -*- coding: utf-8 -*-
# Ant Kitchen level v2: docs/level/level_v2.json -> Source/AntKitchen/LevelV2Data.inl
# The gameplay tables of the v2 layout that the game reads as data (LevelV2.h / LevelV2.cpp): loot spots, heavy prize spots,
# the cover table (human.sees.never_targets), the Human's patrol stops and targeting bounds, sticky / wet zones, the places of
# the main object, the districts and the callouts for the HUD. Everything else of v2 (walls, nests, spawns, pets) is constants
# in the code: see docs/level/LEVEL_V2_INTEGRATION.md.
#   python Tools/level/gen_level_v2_code.py        (after Tools/level/build_level_v2.py; then compile)
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
D = json.load(open(os.path.join(ROOT, 'docs', 'level', 'level_v2.json'), encoding='utf-8'))
OUT = os.path.join(ROOT, 'Source', 'AntKitchen', 'LevelV2Data.inl')
def f(v):
    s = ('%.1f' % float(v)).rstrip('0').rstrip('.')
    if s in ('-0', ''): s = '0'
    return s + ('f' if '.' in s else '.f')
def q(s): return s.replace('\\', '\\\\').replace('"', '\\"')
L = ['// Level v2 gameplay tables. Generated by Tools/level/gen_level_v2_code.py from docs/level/level_v2.json. Do not edit by hand.',
     '// Included by LevelV2.cpp only.', '']
spots = D['loot']['spots']
L += ['// Food spots: x, y, the Z of the surface the food lies on, tier 0..3. %d spots.' % len(spots), 'static const FLevelV2Spot GV2Loot[] =', '{']
for s in spots:
    p = s['p']; L.append('\t{ %s, %s, %s, %d },   // %d %s' % (f(p[0]), f(p[1]), f(p[2]), s['tier_loot'], s['i'], (s.get('label') or s.get('group') or '')))
L += ['};', '', '// Heavy prizes.', 'static const FVector3f GV2Heavy[] =', '{']
for h in D['loot']['heavy']:
    p = h['p']; L.append('\t{ %s, %s, %s },   // %s' % (f(p[0]), f(p[1]), f(p[2]), h['label']))
L += ['};', '', '// Where the main object (the slice of birthday cake) can lie: x, y, z, the chance in percent.', 'static const FLevelV2Main GV2Main[] =', '{']
main = D['loot']['main']
chance = {'M1': 40, 'M2': 40, 'M3': 20}     # the fridge crisper is the rare one
for m in main['spots']:
    p = m['p']; L.append('\t{ %s, %s, %s, %d, TEXT("%s") },   // %s' % (f(p[0]), f(p[1]), f(p[2]), chance[m['id']], q(m['ru']), m['id']))
L += ['};', 'static const int32 GV2MainValue = %d;' % main['value'], 'static const float GV2MainWeightDesign = %s;' % f(main['weight']), '']
cov = [c for c in D['human']['sees']['never_targets'] if c.get('needs_code') or 'hide table' in c.get('src', '')]
cov = [c for c in D['human']['sees']['never_targets'] if 'rect' in c and not c.get('src', '').startswith('HumanAIController')]
L += ['// Cover: an ant inside one of these boxes is neither picked as a target by the Human nor hurt by his stomp, slap and newspaper.',
      '// (The four boxes and the shut-container rule that the code had before stay in AHumanAIController.) %d boxes.' % len(cov),
      'static const FLevelV2Box GV2Cover[] =', '{']
for c in cov:
    r, z = c['rect'], c['z']; L.append('\t{ %s, %s, %s, %s, %s, %s, TEXT("%s") },' % (f(r[0]), f(r[1]), f(z[0]), f(r[2]), f(r[3]), f(z[1]), q(c['ru'])))
L += ['};', '', '// The Human picks targets only inside the house.', 'static const FLevelV2Box GV2TargetBounds[] =', '{']
for r in D['human']['targeting_bounds']:
    L.append('\t{ %s, %s, -400.f, %s, %s, 6000.f, TEXT("") },' % (f(r[0]), f(r[1]), f(r[2]), f(r[3])))
pat = D['human']['patrol']
L += ['};', '', '// The stops of his patrol, in order.', 'static const FVector2f GV2Patrol[] =', '{']
L += ['\t{ %s, %s },' % (f(p[0]), f(p[1])) for p in pat['points']]
L += ['};', 'static const float GV2WanderKitchen[4] = { %s };' % ', '.join(f(v) for v in pat['kitchen_box']),
      'static const float GV2WanderLiving[4] = { %s };' % ', '.join(f(v) for v in pat['living_box']), '']
zones = [h for h in D['hazards'] if h['kind'] in ('sticky', 'wet') and h.get('src', '').startswith('level_v2')]
L += ['// New sticky (0) and wet (1) zones: kind, box (a circle is stored as its bounding box plus the radius; 0 = a box).', 'static const FLevelV2Zone GV2Zones[] =', '{']
for h in zones:
    z = h['z']
    if 'rect' in h: r = h['rect']; box = (r[0], r[1], r[2], r[3]); rad = 0
    else: c = h['circle']; box = (c[0] - c[2], c[1] - c[2], c[0] + c[2], c[1] + c[2]); rad = c[2]
    L.append('\t{ %d, %s, %s, %s, %s, %s, %s, %s },   // %s' % (0 if h['kind'] == 'sticky' else 1, f(box[0]), f(box[1]), f(z[0]), f(box[2]), f(box[3]), f(z[1]), f(rad), h['ru']))
L += ['};', '', '// Districts (floor plan): the name the HUD shows. First match wins; the wall districts come first.', 'static const FLevelV2District GV2Districts[] =', '{']
ds = sorted(D['districts'], key=lambda d: 0 if d['id'] == 'zastenye' else 1)
for d in ds:
    for r in d['rects']:
        L.append('\t{ %s, %s, %s, %s, TEXT("%s") },' % (f(r[0]), f(r[1]), f(r[2]), f(r[3]), q(d['ru'])))
L += ['};', '', '// Callouts: the named nodes of the route graph.', 'static const FLevelV2Callout GV2Callouts[] =', '{']
for n in D['graph']['nodes']:
    p = n['p']; L.append('\t{ %s, %s, %s, TEXT("%s") },' % (f(p[0]), f(p[1]), f(p[2] if len(p) > 2 else 0), q(n['ru'])))
L += ['};', '']
with open(OUT, 'w', encoding='utf-8-sig', newline='') as fo: fo.write('\n'.join(L) + '\n')
print('wrote %s: loot %d, heavy %d, cover %d, patrol %d, zones %d, districts %d rects, callouts %d' % (os.path.relpath(OUT, ROOT), len(spots), len(D['loot']['heavy']), len(cov), len(pat['points']), len(zones), sum(len(d['rects']) for d in D['districts']), len(D['graph']['nodes'])))