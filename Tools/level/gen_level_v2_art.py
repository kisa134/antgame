# -*- coding: utf-8 -*-
# Ant Kitchen level v2: SourceArt/Blender/level_v2/level_v2_manifest.json -> docs/level/KitchenArtData_v2.inl
# The same two C++ tables that Tools/gen_kitchen_art.py writes into Source/AntKitchen/KitchenArtData.inl (GKitchenArt, GKitchenMovers),
# for the v2 layout. A REVIEW COPY: nothing under Source is touched. The programmer copies it over KitchenArtData.inl when v2 goes in
# (see docs/level/LEVEL_V2_INTEGRATION.md).   python Tools/level/gen_level_v2_art.py
# Self-test: the formatter is first run on the rows parsed from the current KitchenArtData.inl and must reproduce that file line for line.
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
M = json.load(open(os.path.join(ROOT, 'SourceArt', 'Blender', 'level_v2', 'level_v2_manifest.json'), encoding='utf-8'))
OLD = open(os.path.join(ROOT, 'docs', 'level', 'v1', 'KitchenArtData.inl'), encoding='utf-8-sig').read().replace('\r\n', '\n')   # the v1 table (frozen)
OUT = os.path.join(ROOT, 'docs', 'level', 'KitchenArtData_v2.inl')
def f(v):
    s = ('%.3f' % v).rstrip('0').rstrip('.')
    if s in ('-0', ''): s = '0'
    return s + ('f' if '.' in s else '.f')
def f6(v):
    s = ('%.6f' % v).rstrip('0').rstrip('.')
    if s in ('-0', ''): s = '0'
    return s + ('f' if '.' in s else '.f')
def axis(v): return '{%s, %s, %s}' % (f6(v[0]), f6(v[1]), f6(v[2]))
def vec(v): return '{%s, %s, %s}' % (f(v[0]), f(v[1]), f(v[2]))
def inst_line(e, n): return '\t{ TEXT("%s"), %d, %d, %d, %s, %s, %s, %s, %s },   // %d' % (e['name'], e['index'], e['role'], e['parent'], vec(e['loc']), axis(e['ax']), axis(e['ay']), axis(e['az']), vec(e['scale']), n)
def mover_line(m, n, e): return '\t{ %d, %d, %s, %s, %s, %d, %s, TEXT("%s"), TEXT("%s") },   // %d %s#%d %s' % (m['inst'], m['type'], vec(m['axis']), f(m['angle']), vec(m['slide']), m['flags'], f(m['auto']), m['open'], m['close'], n, e['name'], e['index'], m.get('note', ''))

# ---- self-test on the current file
def fl(s): return float(s.strip().rstrip('f').rstrip('.') or 0)
def v3(s): return [fl(v) for v in s.split(',')]
rows = [{'name': m.group(1), 'index': int(m.group(2)), 'role': int(m.group(3)), 'parent': int(m.group(4)), 'loc': v3(m.group(5)), 'ax': v3(m.group(6)), 'ay': v3(m.group(7)), 'az': v3(m.group(8)), 'scale': v3(m.group(9))}
        for m in re.finditer(r'\{ TEXT\("(\w+)"\), (\d+), (\d+), (-?\d+), \{([^}]*)\}, \{([^}]*)\}, \{([^}]*)\}, \{([^}]*)\}, \{([^}]*)\} \},', OLD)]
old_lines = set(l.split('   //')[0] for l in OLD.split('\n') if l.startswith('\t{'))
same = sum(1 for n, r in enumerate(rows) if inst_line(r, n).split('   //')[0] in old_lines)
print('self-test: %d of %d instance rows of the current .inl reproduced exactly' % (same, len(rows)))
ok = same == len(rows)

# ---- v2
insts, movers, v1map = [], [], {}
for p in M['pieces']:
    for k, i in enumerate(p['instances']):
        e = {'name': p['name'], 'index': i.get('index', k), 'role': i.get('role', 0), 'parent': -1, 'loc': i['game_loc_uu'], 'ax': i['game_axis_x'], 'ay': i['game_axis_y'], 'az': i['game_axis_z'], 'scale': i.get('scale') or [1, 1, 1], 'src': i}
        if e['role'] == 1:
            mv = i['mover']
            m = {'inst': len(insts), 'type': 0 if mv['type'] == 'hinge' else 1, 'axis': i.get('hinge_axis_game', [0, 0, 1]), 'angle': float(i.get('open_angle_game_deg', 0.0)), 'slide': i.get('slide_game_uu', [0, 0, 0]),
                 'flags': mv['flags'], 'auto': float(mv['auto_close_s']), 'open': mv['open_text'], 'close': mv['close_text'], 'note': ''}
            if 'v1_mover' in mv: v1map[mv['v1_mover']] = len(movers)
            movers.append(m)
        insts.append(e)
for e in insts:
    if e['role'] == 3: e['parent'] = v1map[e['src']['rides_v1_mover']]
L = ['// Level v2 REVIEW COPY, generated by Tools/level/gen_level_v2_art.py from SourceArt/Blender/level_v2/level_v2_manifest.json. Do not edit by hand.',
     '// Same tables and format as KitchenArtData.inl (Tools/gen_kitchen_art.py). %d instances, %d generic movers.' % (len(insts), len(movers)),
     '// Included by KitchenArt.cpp only once it replaces Source/AntKitchen/KitchenArtData.inl.', '', 'static const FKitchenArtInst GKitchenArt[] =', '{']
L += [inst_line(e, n) for n, e in enumerate(insts)]
L += ['};', '', '// Inst, Type (0 hinge, 1 slide), hinge axis (game space), open angle, slide (game space), flags, auto-close seconds, prompts.',
      '// Flags: 1 starts open, 2 needs the fridge door open, 4 needs the dishwasher door open, 8 the Human pushes it shut, 16 the Human may open it, 32 the Human and the pets push it open.',
      'static const FKitchenArtMover GKitchenMovers[] =', '{']
L += [mover_line(m, n, insts[m['inst']]) for n, m in enumerate(movers)]
L += ['};', '']
with open(OUT, 'w', encoding='utf-8-sig', newline='') as fo: fo.write('\r\n'.join(L) + '\r\n')
if '--install' in sys.argv:
    # v2 is in the game: the same table goes to Source (UTF-8 with BOM, LF like the rest of the sources)
    S = ['// Level v2. Generated by Tools/level/gen_level_v2_art.py --install from SourceArt/Blender/level_v2/level_v2_manifest.json. Do not edit by hand.',
         '// (Tools/gen_kitchen_art.py is the v1 generator: do not run it, it would bring the old layout back.)',
         '// Included by KitchenArt.cpp only. %d instances, %d generic movers.' % (len(insts), len(movers))] + L[3:]
    with open(os.path.join(ROOT, 'Source', 'AntKitchen', 'KitchenArtData.inl'), 'w', encoding='utf-8-sig', newline='') as fo: fo.write('\n'.join(S) + '\n')
    print('installed Source/AntKitchen/KitchenArtData.inl')
unchanged = sum(1 for n, e in enumerate(insts) if inst_line(e, n).split('   //')[0] in old_lines)
roles = [sum(1 for e in insts if e['role'] == r) for r in range(4)]
bad = [e['name'] for e in insts if abs(sum(c * c for c in e['ax']) - 1) > 1e-3 or abs(sum(c * c for c in e['az']) - 1) > 1e-3]
print('wrote %s: %d instances (static %d, movers %d, gadget %d, riders %d), %d rows identical to the current table, %d new or moved' % (os.path.relpath(OUT, ROOT), len(insts), roles[0], roles[1], roles[2], roles[3], unchanged, len(insts) - unchanged))
print('non-unit axes: %s' % bad)
sys.exit(0 if ok and not bad else 1)