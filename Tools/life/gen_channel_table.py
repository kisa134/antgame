# Writes Source/AntKitchen/AntLifeChannels.inl from Content/Movies/Life/*.mp4: each channel's length and its picture's mean
# colour 4 times a second (the TV's glow on the room follows it).   python Tools/life/gen_channel_table.py
import os, subprocess, json
HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.abspath(os.path.join(HERE, "..", ".."))
MOV = os.path.join(PROJ, "Content", "Movies", "Life")
CH = [("ch0_cartoon", "Мультик «Кот Пирожок»", "KCartoon"), ("ch1_nature", "«Царство муравьёв»", "KNature"), ("ch2_news", "«Новости часа»", "KNews"),
      ("ch3_sport", "Футбол: Лига Дворов", "KSport"), ("ch4_ad", "Реклама «Белая Погода»", "KAd"), ("ch5_cooking", "«Вкусно за 5 минут»", "KCooking"),
      ("ch6_kids", "Канал «Карапуз»", "KKids"), ("ch7_birds", "Природа HD: птицы", "KBirds"), ("ch8_nosignal", "Нет сигнала", "KStatic")]
lines = ["// Generated by Tools/life/gen_channel_table.py from Content/Movies/Life (do not edit by hand).", "namespace AntLifeData", "{"]
rows = []
for cid, ru, kind in CH:
    f = os.path.join(MOV, cid + ".mp4")
    if not os.path.exists(f):
        print("missing", cid); continue
    secs = float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", f], capture_output=True, text=True).stdout.strip())
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", f, "-vf", "fps=4,scale=8:8:flags=area,scale=1:1:flags=area", "-f", "rawvideo", "-pix_fmt", "rgb24", "-"], capture_output=True).stdout
    vals = list(raw)
    lines.append("\tstatic const uint8 C_%s[] = { %s };" % (cid, ", ".join(str(v) for v in vals)))
    rows.append('\t\t{ TEXT("%s"), TEXT("%s"), %.3ff, AntLife::%s, C_%s, %d },' % (cid, ru, secs, kind, cid, len(vals) // 3))
    print("CHAN", cid, round(secs, 2), len(vals) // 3)
lines.append("\tstatic const AntLife::FChannel Channels[] =")
lines.append("\t{")
lines += rows
lines.append("\t};")
lines.append("}")
open(os.path.join(PROJ, "Source", "AntKitchen", "AntLifeChannels.inl"), "w", encoding="utf-8-sig").write("\n".join(lines) + "\n")
print("TABLE DONE")
