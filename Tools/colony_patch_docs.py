import io, sys
D = r"C:\Users\HYPERPC\Documents\Unreal Projects\AntKitchen_colony\docs"

def edit(name, fn):
    p = D + "\\" + name
    t = io.open(p, encoding="utf-8-sig").read()
    nl = "\r\n" if "\r\n" in t else "\n"
    t = fn(t.replace("\r\n", "\n"))
    io.open(p, "w", encoding="utf-8-sig", newline="").write(t.replace("\n", nl))

