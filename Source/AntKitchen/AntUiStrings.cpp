	const FString& L(const TCHAR* Key)
	{
		static TMap<FString, TPair<FString, FString>> Map;
		static FString Missing;
		if (Map.Num() == 0)
		{
			for (const FUiString& S : Table) { Map.Add(S.Key, TPair<FString, FString>(S.Ru, S.En)); }
		}
		if (const TPair<FString, FString>* P = Map.Find(Key))
		{
			return Lang() == 1 ? P->Value : P->Key;
		}
		Missing = Key;
		return Missing;
	}
